"""Generates a self-contained Kaggle task file from the repo.

The scorer (scoring/answers.py + scoring/score.py) is copied in verbatim
between BEGIN/END SCORER markers; tests/test_generated_task.py checks the
copy scores exactly like the repo scorer. Items are embedded as JSON.

Usage:
  python kaggle/build_task.py --name pilot-ves-label --stations ID,ID,... --repeats 2
  python kaggle/build_task.py --name ves-no-label --task no_label --slice real
"""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "kaggle" / "generated"
MAX_TOKENS = 4096

HEADER = '''# Generated by kaggle/build_task.py from github.com/dannwaneri/ves-label-benchmark
# Do not edit by hand. Scoring is deterministic code; no model judges.
# %%
import json

import kaggle_benchmarks as kbench
import pandas as pd

TASK_NAME = {name!r}
MAX_TOKENS = {max_tokens}
REPEATS = {repeats}
'''

SCORER_START = "# ===== BEGIN SCORER (verbatim copy of scoring/answers.py + scoring/score.py) ====="
SCORER_END = "# ===== END SCORER ====="

BODY = '''
# %%
ITEMS = json.loads(r\'\'\'{items_json}\'\'\')
ITEMS_BY_ID = {{it["id"]: it for it in ITEMS}}
ROWS = pd.DataFrame([{{"item_id": it["id"], "rep": r}} for r in range(1, REPEATS + 1) for it in ITEMS])


# %%
@kbench.task(name="{name}-item", store_task=False)
def ves_item(llm, item_id: str, rep: int) -> dict:
    item = ITEMS_BY_ID[item_id]
    reply = llm.prompt(item["prompt"], extra_api_params={{"max_tokens": MAX_TOKENS}})
    s = score_item(item, reply)
    print("ITEM_RESULT " + json.dumps({{"item_id": item_id, "rep": rep, "pass": s["pass"],
                                        "status": s["status"], "reply": reply}}))
    return {{"item_id": item_id, "rep": rep, "reply": reply, "pass": s["pass"]}}


@kbench.task(name="{name}")
def main_task(llm) -> float:
    runs = ves_item.evaluate(llm=[llm], evaluation_data=ROWS, n_jobs=4,
                             on_failure="continue", max_attempts=2, retry_delay=10)
    for run in runs.errored_runs:
        print("ITEM_ERROR " + json.dumps({{"params": str(run.params), "error": str(run.error_message)[:300]}}))
    done = [r for r in runs.completed_runs.as_dataframe().result]
    # Score = {score_doc}
    by_rep = {{}}
    for d in done:
        by_rep.setdefault(d["rep"], []).append(d)
    per_rep = []
    for rep, ds in sorted(by_rep.items()):
        scored = [score_item(ITEMS_BY_ID[d["item_id"]], d["reply"]) for d in ds]
        agg = aggregate([ITEMS_BY_ID[d["item_id"]] for d in ds], scored)
        print("SUMMARY rep=%d %s" % (rep, json.dumps(agg)))
        per_rep.append({score_expr})
    n_expected = len(ROWS)
    print("COMPLETED %d/%d" % (len(done), n_expected))
    # Missing (errored) items count as failures: divide by the expected count.
    return float(sum(per_rep) / REPEATS) if per_rep else 0.0


main_task.run(kbench.llm)
'''

SCORE_EXPR = {
    # mean item pass rate (pilot): every item counts once per repeat
    "items": ('mean item pass rate over all items, averaged over repeats',
              'sum(s["pass"] for s in scored) / len(ITEMS)'),
}


def scorer_source():
    parts = []
    for name in ("answers.py", "score.py"):
        src = (ROOT / "scoring" / name).read_text(encoding="utf-8")
        src = "\n".join(ln for ln in src.splitlines() if not ln.startswith("from scoring."))
        parts.append(f"# --- scoring/{name} ---\n{src}")
    return "\n\n".join(parts)


def select(items, stations=None, task=None, slice_name=None):
    out = items
    if stations:
        out = [it for it in out if it["station_id"] in stations]
        missing = set(stations) - {it["station_id"] for it in out}
        assert not missing, f"unknown stations: {missing}"
    if task:
        out = [it for it in out if it["task"] == task]
    if slice_name:
        out = [it for it in out if it["slice"] == slice_name]
    assert out, "no items selected"
    return out


def build(name, items, repeats, score="items"):
    keep = ("id", "slice", "synthetic", "station_id", "station", "task", "twin", "framing",
            "derived", "label", "label_truth", "wrong_kind", "n_layers", "prompt")
    items_json = json.dumps([{k: it[k] for k in keep} for it in items], ensure_ascii=True)
    assert "'''" not in items_json
    doc, expr = SCORE_EXPR[score]
    code = (HEADER.format(name=name, max_tokens=MAX_TOKENS, repeats=repeats)
            + "\n# %%\n" + SCORER_START + "\n" + scorer_source() + "\n" + SCORER_END + "\n"
            + BODY.format(items_json=items_json, name=name, score_doc=doc, score_expr=expr))
    assert re.fullmatch(r"[a-z0-9-]+", name)
    return code


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True)
    ap.add_argument("--stations")
    ap.add_argument("--task")
    ap.add_argument("--slice")
    ap.add_argument("--repeats", type=int, default=1)
    args = ap.parse_args()
    items = json.loads((ROOT / "items" / "items.json").read_text(encoding="utf-8"))["items"]
    stations = args.stations.split(",") if args.stations else None
    chosen = select(items, stations, args.task, args.slice)
    code = build(args.name, chosen, args.repeats)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / f"{args.name}.py"
    path.write_text(code, encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}: {len(chosen)} items x {args.repeats} repeats")


if __name__ == "__main__":
    main()
