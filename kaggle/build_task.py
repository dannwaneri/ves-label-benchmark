"""Generates a self-contained Kaggle task file from the repo.

The scorer (scoring/answers.py, score.py, uncued.py, dispatch.py) is copied
in verbatim between BEGIN/END SCORER markers; tests/test_generated_task.py
checks the copy scores exactly like the repo scorer. Items are embedded as JSON.

In the task, each item is asked in a fresh chat. If the reply is incomplete
(empty or cut off, see scoring/dispatch.py) it is asked once more in another
fresh chat -- one bounded retry. Infrastructure failures are excluded from
the score and printed.

Usage:
  python kaggle/build_task.py --name probe-ves-uncued --items items/probe_items.json
  python kaggle/build_task.py --name pilot-ves-label --stations ID,ID --repeats 2
"""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "kaggle" / "generated"
MAX_TOKENS = 16000
SCORER_MODULES = ("answers.py", "score.py", "uncued.py", "dispatch.py")

HEADER = '''# Generated by kaggle/build_task.py (ves-label-benchmark). Do not edit by hand.
# Scoring is deterministic code; no model judges.
# %%
import json

import kaggle_benchmarks as kbench
import pandas as pd

MAX_TOKENS = {max_tokens}
REPEATS = {repeats}
'''

SCORER_START = "# ===== BEGIN SCORER (verbatim copy of scoring/*.py) ====="
SCORER_END = "# ===== END SCORER ====="

BODY = '''
# %%
ITEMS = json.loads(r\'\'\'{items_json}\'\'\')
ITEMS_BY_ID = {{it["id"]: it for it in ITEMS}}
ROWS = pd.DataFrame([{{"item_id": it["id"], "rep": r}} for r in range(1, REPEATS + 1) for it in ITEMS])


def ask(llm, item):
    """Fresh chat per attempt; at most one retry for an incomplete reply."""
    replies = []
    for attempt in (1, 2):
        with kbench.chats.new(f"attempt-{{attempt}}"):
            reply = llm.prompt(item["prompt"], extra_api_params={{"max_tokens": MAX_TOKENS}})
        replies.append(reply)
        if not incomplete(item, reply):
            break
    return replies


# %%
@kbench.task(name="{name}-item", store_task=False)
def ves_item(llm, item_id: str, rep: int) -> dict:
    item = ITEMS_BY_ID[item_id]
    replies = ask(llm, item)
    s = score_any(item, replies[-1])
    print("ITEM_RESULT " + json.dumps({{"item_id": item_id, "rep": rep, "attempts": len(replies),
                                        "status": s["status"], "pass": s["pass"], "replies": replies}}))
    return {{"item_id": item_id, "rep": rep, "attempts": len(replies), "reply": replies[-1],
            "status": s["status"], "pass": s["pass"]}}


@kbench.task(name="{name}")
def main_task(llm) -> float:
    runs = ves_item.evaluate(llm=[llm], evaluation_data=ROWS, n_jobs=4, on_failure="continue")
    for run in runs.errored_runs:
        print("ITEM_ERROR " + json.dumps({{"params": str(run.params), "error": str(run.error_message)[:300]}}))
    done = list(runs.completed_runs.as_dataframe().result)
    scored = [d for d in done if d["status"] != "infra"]
    infra = len(done) - len(scored)
    print("COMPLETED %d/%d  infra_failures=%d  errored=%d" % (len(done), len(ROWS), infra, len(runs.errored_runs)))
    # Score: pass rate over items with a complete reply (infra failures excluded, reported above).
    return float(sum(d["pass"] for d in scored) / len(scored)) if scored else 0.0


main_task.run(kbench.llm)
'''


def scorer_source():
    parts = []
    for name in SCORER_MODULES:
        src = (ROOT / "scoring" / name).read_text(encoding="utf-8")
        src = "\n".join(ln for ln in src.splitlines() if not ln.startswith("from scoring."))
        parts.append(f"# --- scoring/{name} ---\n{src}")
    return "\n\n".join(parts)


def build(name, items, repeats=1):
    assert re.fullmatch(r"[a-z0-9-]+", name)
    items_json = json.dumps(items, ensure_ascii=True)
    assert "'''" not in items_json
    return (HEADER.format(max_tokens=MAX_TOKENS, repeats=repeats)
            + "\n# %%\n" + SCORER_START + "\n" + scorer_source() + "\n" + SCORER_END + "\n"
            + BODY.format(items_json=items_json, name=name))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True)
    ap.add_argument("--items", default="items/items.json")
    ap.add_argument("--stations")
    ap.add_argument("--task")
    ap.add_argument("--repeats", type=int, default=1)
    args = ap.parse_args()
    items = json.loads((ROOT / args.items).read_text(encoding="utf-8"))["items"]
    if args.stations:
        keep = set(args.stations.split(","))
        items = [it for it in items if it.get("station_id") in keep]
    if args.task:
        items = [it for it in items if it.get("task") == args.task]
    assert items, "no items selected"
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / f"{args.name}.py"
    path.write_text(build(args.name, items, args.repeats), encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}: {len(items)} items x {args.repeats} repeats")


if __name__ == "__main__":
    main()
