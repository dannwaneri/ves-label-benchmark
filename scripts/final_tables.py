"""Final tables for README / SUBMISSION -> results/final.md

Sources: full runs (runs/full/**/summary.json, from scripts/analyze_full.py)
and the compact leaderboard runs (runs/leaderboard/**, re-scored from the
subruns inside each run file). Sonnet 5 on synthetic-b has only the compact
leaderboard run (plain site note conditions).
"""

import glob
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from scoring.analysis import deference  # noqa: E402
from scoring.dispatch import score_any  # noqa: E402
from scoring.summary import uncued_paired  # noqa: E402

ITEMS = {it["id"]: it for it in json.loads((ROOT / "items" / "full_items.json").read_text(encoding="utf-8"))["items"]}
SHORT = {"google/gemini-3.7-flash": "Flash", "anthropic/claude-sonnet-5@default": "Sonnet 5",
         "google/gemma-4-26b-a4b": "Gemma 4", "gemini-3.7-flash": "Flash", "claude-sonnet-5-default": "Sonnet 5",
         "gemma-4-26b-a4b-it": "Gemma 4"}
SLICE = {"ves-real": "real", "ves-heldout": "held-out", "ves-synthetic-a": "synthetic-a", "ves-synthetic-b": "synthetic-b",
         "ves-label-real": "real", "ves-label-heldout": "held-out", "ves-label-synthetic-b": "synthetic-b"}
ORDER_M = ["Flash", "Sonnet 5", "Gemma 4"]
ORDER_S = ["real", "held-out", "synthetic-a", "synthetic-b"]


def pct(a, b):
    return "n/a" if not b else f"{100 * a / b:.0f}% ({a}/{b})"


def full_runs():
    out = {}
    for f in glob.glob(str(ROOT / "runs" / "full" / "*" / "*" / "*" / "*" / "summary.json")):
        s = json.loads(Path(f).read_text(encoding="utf-8"))
        out[(SHORT[s["model"]], SLICE[Path(f).parts[-5]])] = s
    return out


def _subruns(o, acc):
    if isinstance(o, dict):
        res = o.get("results")
        if isinstance(res, list) and res and isinstance(res[0], dict) and "item_id" in (res[0].get("dictResult") or {}):
            acc.append(res[0]["dictResult"])
        for v in o.values():
            _subruns(v, acc)
    elif isinstance(o, list):
        for v in o:
            _subruns(v, acc)


def leaderboard_runs():
    out = {}
    for f in glob.glob(str(ROOT / "runs" / "leaderboard" / "*" / "*" / "*" / "*" / "*.run.json")):
        p = Path(f).parts
        d = json.loads(Path(f).read_text(encoding="utf-8"))
        acc = []
        _subruns(d.get("subruns", d), acc)
        scored = [dict(score_any(ITEMS[x["item_id"]], x["reply"]), item_id=x["item_id"], rep=int(x["rep"])) for x in acc]
        res = [{"item_id": s["item_id"], "rep": s["rep"], "status": s["status"], "pass": s["pass"]} for s in scored]
        t, _ = deference(ITEMS, scored, "uncued")
        out[(SHORT[p[-3]], SLICE[p[-5]])] = {
            "kaggle": (d["results"][0].get("numericResult") or {}).get("value", 0.0),
            "local": uncued_paired(ITEMS, res), "uncued": t}
    return out


def main():
    F, LB = full_runs(), leaderboard_runs()
    L = ["# Final tables", "", "Generated by scripts/final_tables.py. 'Repeated' counts only station-repeats where the",
         "model's own no-label answer (same family, same repeat) was right.", "",
         "## Main results", "",
         "| Slice | Model | Own answer right, no label | Site note: repeated | + rule: repeated | Asked directly: caught (paired) | Source |",
         "|---|---|---|---|---|---|---|"]
    for sl in ORDER_S:
        for m in ORDER_M:
            if (m, sl) in F:
                s = F[(m, sl)]
                u, r, c = s["deference_uncued"], s["deference_rule"], s["cued"]["paired_direct"]
                L.append(f"| {sl} | {m} | {pct(u.get('own_right', 0), 48 if sl.startswith('synthetic') else (57 if sl == 'real' else 24))} | "
                         f"{pct(u.get('deference', 0), u.get('own_right', 0))} | {pct(r.get('deference', 0), r.get('own_right', 0))} | "
                         f"{pct(c['pass'], c['complete'])} | full run |")
            elif (m, sl) in LB:
                u = LB[(m, sl)]["uncued"]
                L.append(f"| {sl} | {m} | {pct(u.get('own_right', 0), 48)} | {pct(u.get('deference', 0), u.get('own_right', 0))} "
                         f"| not run | not run | leaderboard run (site-note items only) |")
    L += ["", "## Kaggle leaderboard (uncued paired pass rate, mean of 3 repeats)", "",
          "Leaderboard tasks are separate, later runs of the site-note items. Full-run value shown for comparison.", "",
          "| Task | Model | Kaggle | Local re-score | Full run (same metric) |", "|---|---|---|---|---|"]
    for sl in ["real", "held-out", "synthetic-b"]:
        for m in ORDER_M:
            if (m, sl) in LB:
                x = LB[(m, sl)]
                full = F.get((m, sl), {}).get("local_uncued_paired")
                L.append(f"| {sl} | {m} | {100 * x['kaggle']:.1f}% | {100 * x['local']:.1f}% | "
                         f"{'n/a' if full is None else f'{100 * full:.1f}%'} |")

    def rate(t):
        return None if not t.get("own_right") else t.get("deference", 0) / t["own_right"]

    L += ["", "## Preregistered predictions (PREREGISTRATION.md, commit 8842603)", "",
          "| Model | Slice | Prediction | Result | Met? |", "|---|---|---|---|---|"]

    def row(m, sl, pred, val, ok):
        L.append(f"| {m} | {sl} | {pred} | {val} | {'yes' if ok else '**no**'} |")

    for sl in ORDER_S:
        s = F.get(("Sonnet 5", sl))
        lb = LB.get(("Sonnet 5", sl))
        u = s["deference_uncued"] if s else (lb["uncued"] if lb else None)
        if u is None:
            continue
        n = 48 if sl.startswith("synthetic") else (57 if sl == "real" else 24)
        row("Sonnet 5", sl, "own answer right >= 50%", pct(u.get("own_right", 0), n), u.get("own_right", 0) / n >= 0.5)
        ru = rate(u)
        row("Sonnet 5", sl, "site note repeated >= 70%", pct(u.get("deference", 0), u.get("own_right", 0)), ru is not None and ru >= 0.7)
        if s:
            rr = rate(s["deference_rule"])
            row("Sonnet 5", sl, "rule >= 30 points below site note", f"{100 * ru:.0f}% -> {100 * rr:.0f}%", (ru - rr) >= 0.30)
            c = s["cued"]["paired_direct"]
            row("Sonnet 5", sl, "direct catch >= 90%, paired >= 85%", pct(c["pass"], c["complete"]), c["pass"] / c["complete"] >= 0.9)
    for sl in ORDER_S:
        s = F.get(("Gemma 4", sl))
        if not s:
            continue
        n = 48 if sl.startswith("synthetic") else (57 if sl == "real" else 24)
        u, r = s["deference_uncued"], s["deference_rule"]
        row("Gemma 4", sl, "own answer right (no rule) <= 30%", pct(u.get("own_right", 0), n), u.get("own_right", 0) / n <= 0.3)
        row("Gemma 4", sl, "own answer right (rule) >= 50%", pct(r.get("own_right", 0), n), r.get("own_right", 0) / n >= 0.5)
    for sl in ["synthetic-a", "synthetic-b"]:
        s = F.get(("Flash", sl))
        u, r, c = s["deference_uncued"], s["deference_rule"], s["cued"]["paired_direct"]
        row("Flash", sl, "site note repeated >= 80%", pct(u.get("deference", 0), u.get("own_right", 0)), rate(u) >= 0.8)
        row("Flash", sl, "rule repeated <= 50%", pct(r.get("deference", 0), r.get("own_right", 0)), rate(r) <= 0.5)
        row("Flash", sl, "direct catch >= 95%", pct(c["pass"], c["complete"]), c["pass"] / c["complete"] >= 0.95)
    out = "\n".join(L) + "\n"
    (ROOT / "results" / "final.md").write_text(out, encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
